const BUILDERS: Record<BodyPlan, (id: SpeciesId) => Plan> = {
  raptor, theropod, spino: () => spino(), ceratops: () => ceratops(), ankylo: () => ankylo(), stego: () => stego(), hadro,
  pachy: () => pachy(), theriz: () => theriz(), sauropod: () => sauropod(),
  wolf: () => wolf(), cat, bear: () => bear(), croc: () => croc(), bird: () => bird(), rhino: () => rhino(),
  mammoth: () => mammoth(), ape: () => ape(),
  harpy: () => harpy(), minotaur: () => minotaur(), serpent: () => serpent(), giant: () => giant(),
  manticore: () => manticore(), hydra: () => hydra(), wraith: () => wraith(), wyvern: () => wyvern(), mandrake: () => mandrake(),
};

const cache = new Map<SpeciesId, Plan>();

export function planFor(species: SpeciesId): Plan {
  let p = cache.get(species);
  if (!p) {
    const sp = SPECIES[species];
    p = (BUILDERS[sp?.body ?? 'raptor'] ?? raptor)(species);
    cache.set(species, p);
  }
  return p;
}

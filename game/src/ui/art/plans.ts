// Body plans for the procedural creature art (DinoArt). One plan per SpeciesDef.body, with
// species-specific tweaks (horns, heavier heads, arm size, crests). Authored in a 240×160 box,
// side view facing right, ground at y≈148.
//
// Colour regions (ARK): 0 main body, 1 underbelly, 2 pattern, 3 crest/frill/sail/horns,
// 4 back plates/spikes/feathers, 5 eyes & claws.

import type { BodyPlan, SpeciesId } from '../../engine/types';
import { SPECIES } from '../../engine/data/species';
import { blob, circle, ellipse, horn, plate, poly, quill, smoothOpen, teeth, tube, type P2 } from './geom';

export type Region = 0 | 1 | 2 | 3 | 4 | 5 | 'bone' | 'dark' | 'shade' | 'mouth' | 'light' | 'horn';

export interface Shape {
  d: string;
  r: Region;
  /** opacity */
  o?: number;
  /** draw as a stroke instead of a fill */
  line?: number;
  /** skip the per-shape shading overlay */
  flat?: boolean;
}

export type PatternKind = 'stripes' | 'spots' | 'bands' | 'saddle' | 'none';

export interface Plan {
  far: Shape[];
  behind: Shape[];
  body: string[];
  belly?: string;
  over: Shape[];
  near: string[];
  nearOver: Shape[];
  head: {
    pivot: P2;
    behind: Shape[];
    main: string[];
    belly?: string;
    over: Shape[];
    eye: [number, number, number];
    mouth?: string;
    teeth?: string;
    /** glowing eyes (mythic) */
    glow?: boolean;
  };
  pattern: PatternKind;
  patternBox: [number, number, number, number];
  anchors: { rider: P2; helmet: [number, number, number, number]; glint: P2; band: string };
  bust: [number, number, number, number];
  ground: number;
  cx: number;
  shadowW: number;
  /** floats above the ground (wraith) */
  floating?: boolean;
}

const S = (d: string, r: Region, extra: Partial<Shape> = {}): Shape => ({ d, r, ...extra });
const legFoot = (pts: [number, number, number][], toe: [number, number]): string[] => {
  const last = pts[pts.length - 1];
  return [tube(pts), tube([[last[0] - 2, last[1], last[2]], [toe[0], toe[1], Math.max(2.5, last[2] * 0.6)]])];
};
const toeClaws = (x: number, y: number, n = 3, len = 5, step = 4): string => {
  let d = '';
  for (let i = 0; i < n; i++) d += horn([x + i * step, y - 1.5], [x + i * step + len, y + 1], 2.6, -0.6);
  return d;
};


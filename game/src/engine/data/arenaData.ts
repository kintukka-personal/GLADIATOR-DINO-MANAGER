export function makeFoe(spec: FoeSpec, week: number): Creature {
  if ('legend' in spec) return buildNamed(LEGENDS[spec.legend], week);
  if ('named' in spec) return buildNamed(spec.named, week);
  const c = generateBeast(spec.beast, { variant: spec.variant ?? 'standard', name: spec.name, sex: 'M' });
  if (spec.level && spec.level > 1) setLevelAndStats(c, spec.level);
  for (const t of spec.traits ?? []) addTrait(c, t);
  return c;
}


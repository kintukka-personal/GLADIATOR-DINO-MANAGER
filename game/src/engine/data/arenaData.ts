/** Build a named fighter from a spec with an exact raw stat line. */
export function buildNamed(spec: NamedSpec, week = 1): Creature {
  const stats = { ...spec.stats };
  if (spec.hpPerWeeks) stats.hp += Math.floor(Math.max(0, week) / spec.hpPerWeeks);
  const c = makeNamed(spec.species, spec.name, stats, {
    level: spec.level, traits: spec.traits, techniques: spec.techniques, cls: spec.cls, legend: spec.key, price: spec.price,
    eqAge: spec.eqAge, sex: spec.sex ?? 'M',
  });
  if (spec.classXp !== undefined) c.classXp = spec.classXp;
  if (spec.fame) c.fame = spec.fame;
  if (spec.prof) for (const [k, v] of Object.entries(spec.prof)) c.prof[k as WeaponFamily] = v ?? 0;
  if (spec.speciesLevel) c.speciesLevel = spec.speciesLevel;
  if (spec.albino) c.genes.colors = c.genes.colors.map((_, i) => (i === 5 ? 15 : 39));
  if (spec.gear?.length) c.notes = [...(c.notes ?? []), ...spec.gear.map(gearNote)];
  return c;
}


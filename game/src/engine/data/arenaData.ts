// ---------------------------------------------------------------------------
// Gear notes: scripted and foreign fighters have no house armory, so their kit is written into
// creature.notes as "gear:<slot>:<type>:<quality>:<augment>:<unique>" and rebuilt into a transient
// armory when they fight (tournaments.ts). The house name of a temporary entry is "house:<name>".
// ---------------------------------------------------------------------------

export interface GearSpec { slot: GearSlot; type: GearTypeId; quality: Quality; augment?: Augment; unique?: string }

export function gearNote(g: GearSpec): string {
  return `gear:${g.slot}:${g.type}:${g.quality}:${g.augment ?? ''}:${g.unique ?? ''}`;
}

export function parseGearNote(note: string): GearSpec | null {
  if (!note.startsWith('gear:')) return null;
  const [, slot, type, q, augment, unique] = note.split(':');
  if (!slot || !type) return null;
  return {
    slot: slot as GearSlot, type: type as GearTypeId, quality: Math.max(0, Math.min(5, Number(q) || 0)) as Quality,
    augment: (augment || undefined) as Augment | undefined, unique: unique || undefined,
  };
}

export const houseNote = (name: string): string => `house:${name}`;

